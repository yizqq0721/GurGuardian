package com.purr.furguardian.nutrition.model;

public class GuaranteedAnalysis {
    private Double moistureMax;
    private Double crudeProteinMin;
    private Double crudeFatMin;
    private Double crudeFatMax;
    private Double crudeFiberMax;
    private Double ashMax;
    private Double calciumMin;
    private Double phosphorusMin;
    private Double taurineMin;
    private Double lysineMin;

    public Double getMoistureMax() { return moistureMax; }
    public void setMoistureMax(Double moistureMax) { this.moistureMax = moistureMax; }
    public Double getCrudeProteinMin() { return crudeProteinMin; }
    public void setCrudeProteinMin(Double crudeProteinMin) { this.crudeProteinMin = crudeProteinMin; }
    public Double getCrudeFatMin() { return crudeFatMin; }
    public void setCrudeFatMin(Double crudeFatMin) { this.crudeFatMin = crudeFatMin; }
    public Double getCrudeFatMax() { return crudeFatMax; }
    public void setCrudeFatMax(Double crudeFatMax) { this.crudeFatMax = crudeFatMax; }
    public Double getCrudeFiberMax() { return crudeFiberMax; }
    public void setCrudeFiberMax(Double crudeFiberMax) { this.crudeFiberMax = crudeFiberMax; }
    public Double getAshMax() { return ashMax; }
    public void setAshMax(Double ashMax) { this.ashMax = ashMax; }
    public Double getCalciumMin() { return calciumMin; }
    public void setCalciumMin(Double calciumMin) { this.calciumMin = calciumMin; }
    public Double getPhosphorusMin() { return phosphorusMin; }
    public void setPhosphorusMin(Double phosphorusMin) { this.phosphorusMin = phosphorusMin; }
    public Double getTaurineMin() { return taurineMin; }
    public void setTaurineMin(Double taurineMin) { this.taurineMin = taurineMin; }
    public Double getLysineMin() { return lysineMin; }
    public void setLysineMin(Double lysineMin) { this.lysineMin = lysineMin; }
}
